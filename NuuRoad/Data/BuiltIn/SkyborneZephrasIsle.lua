-- share one guide; a step for one side carries `only`.
--
-- Sources:
--   * NPC IDs were read from Wowhead's Forever database (wowhead.com/forever, the
--     Zephras Isle zone page and each quest's start and end NPC, read 2026-09-26). Names
--     follow Wowhead where two sources spell one differently (Tephri Thriceforged,
--     Antelariaa Cloudgaze, Peacekeeper Vaaniel). Windshaper Elementalist and Windshaper
--     Guardian are not in that database, so the Catching Wind step names them in its
--     note only.
--   * The Alliance storyline from The Turncoat to The Magical City of Dalaran, so an
--     Alliance player reaches Dalaran with that quest in hand. Its Avenged Tenfold side
--     quest stays out.
--   * The Horde storyline after the Shadowgale camp, from The Broken Construct's second part
--     through A Firm Response, Blood for Blood, the Tower Defense to Confront Lorthuna chain
--     and The Earthen Ring. These steps follow a recorded Horde Warrior run (NuuRoad session
--     log, 2026-09-26): its order, NPC and item IDs, coordinates, and the objective counts
--     the client showed. The chain from Tower Defense on is the Alliance one, reached later.
--   * Mercy Falls on Deaf Ears is placed at the Shadowgale camp, where the recorded run
--     took it.
--   * World coordinates (Dalaran, Stormwind, Mulgore, Thunder Bluff and Orgrimmar) were
--     converted to map percentages with the client's own map frames (UiMapAssignment,
--     Tools/ClientMap/maps.py); Tal and Thrall land within 0.05 of the spots the other
--     packaged guides already use, which are kept.
--
-- Recorded choices:
--   * No macros (crafting, Walk on Air, /sit, leave vehicle): guides carry none. The
--     step says what to press.
--   * Dying shortcuts are notes offered to players without hardcore rules, never an
--     instruction.
--   * The subzones the route depends on are named by text, matching what the client
--     shows, rather than by ID.
--   * "Accept on the way / climb the tower / accept again" is one step with the way up
--     in its note.
--   * Gathering tool purchases (Herb Pouch, Mining Pick and Pack, Skinning Knife and
--     Satchel) happen once, on the first vendor visit, for both factions.
--   * The Druid chain after Strength and Mercy is not routed; the route accepts
--     Strength and Mercy and leaves it in the log. The Fate of the Den and Crab Season
--     are turned in by both factions.
--   * Tools/CompareGuideOrder.lua reports steps inside a group (their order is the
--     player's), the Alliance and Horde halves of Valanaar and the Shriekling cave in the
--     other order (no character sees both), and The Forest's Bounty handed in after the
--     feather camp rather than between two visits to it: the camp's work is one group here.
--   * The crystal clicks ride along with the Agitators kills, and the Ursera Scavengers
--     with Urs'anah; each is one group here.
--   * Tools/CheckGroups.lua still reports these, kept apart on purpose: Halaan's accept at
--     the top of the tower after the turn-in below it; the class trainers' turn-ins beside
--     Rorian and in the village (each with its training after it); Rorian's Aetheen of the Gales,
--     with the Druid and Mage trainers between; the Scrawny Ursera on the way to the den,
--     before Urs'anah; the Horde High Order Apprentices, their own camp short of the
--     bandits; the Vulgara turn-in after the Warrior trainer and before its "you skipped
--     it" note; the Bloody Note, beside Kaldris rather than at the tower; Elaadrin's
--     turn-in, which ends in a scene; Fillion's two parts, found then carried out; and
--     Hyusaa, up the stairs once the camp is cleared.
--   * Steps that would gate on item count, money, XP, a cooldown or a trainer visit use
--     `now` terms instead, so the guide passes over the books, tools and trainer visits
--     that do not apply rather than waiting on them.
--   * Warriors of both factions turn in The Skybreaker Bulwark on the hearth back to
--     Valanaar after the Shadowgale camp.
--   * The Warrior's Path is turned in to Blademaster Ren as soon as it is taken, as the
--     recorded run did, with a trainer visit for Charge and Rend at level 4 on the way back.
--   * Turn-ins of optional quests (the Camping 101 set, the bounty, the pelts) are `now`
--     gated: passed over when not ready on arrival, not waited on, since the recorded run
--     had to press past every Camping 101 turn-in for a profession it never took.
--   * Making Our Move asks for 7 of each Al'Aketh.
--   * Class training is a `learn` step on the spell IDs each class needs, done once the
--     client knows them; the Shaman visits stay notes. Skysight and Read Ley Line at a
--     convergence or ley line are `cast` steps, done on the cast.
--
